def get_anthropic_api_key() -> str:
    key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not key:
        cfg = load_config()
        key = cfg.get("anthropic", {}).get("api_key", "")
    if not key:
        raise RuntimeError(
            "ANTHROPIC_API_KEY not set. "
            "Set the environment variable or add anthropic.api_key to config.json"
        )
    return key


def load_market_data(briefing_type: str) -> dict:
    path = DATA_DIR / f"latest_{briefing_type}.json"
    if not path.exists():
        raise FileNotFoundError(f"Market data not found: {path}")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def load_news_summary(briefing_type: str) -> dict:
    path = DATA_DIR / f"news_summary_{briefing_type}.json"
    if not path.exists():
        return {}
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    today = datetime.now(KST).strftime("%Y-%m-%d")
    generated = data.get("generated_at", "")[:10]
    if generated != today:
        print(f"[call_claude] 뉴스 파일 날짜 불일치 ({generated} ≠ {today}) — 무시", file=sys.stderr)
        return {}
    return data


def save_analysis(briefing_type: str, analysis: dict) -> None:
    path = DATA_DIR / f"analysis_{briefing_type}.json"
    analysis["generated_at"] = datetime.now(KST).isoformat()
    with open(path, "w", encoding="utf-8") as f:
        json.dump(analysis, f, ensure_ascii=False, indent=2)
    print(f"[call_claude] Saved → {path}")


def extract_json(text: str) -> dict:
    """Parse JSON from Claude's response, stripping any accidental markdown fences or trailing text."""
    text = text.strip()
    # Strip markdown code fences if present
    if text.startswith("```"):
        lines = text.split("\n")
        text = "\n".join(lines[1:-1] if lines[-1].strip() == "```" else lines[1:])
        text = text.strip()
    # Extract only the JSON object (first { ... matching }) to handle trailing text
    start = text.find("{")
    if start != -1:
        depth = 0
        in_str = False
        escape = False
        for i, ch in enumerate(text[start:], start):
            if escape:
                escape = False
                continue
            if ch == "\\" and in_str:
                escape = True
                continue
            if ch == '"':
                in_str = not in_str
                continue
            if not in_str:
                if ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
                    if depth == 0:
                        text = text[start:i + 1]
                        break
    data = json.loads(text)

    # Guarantee up_pct + down_pct == 100
    pred = data.get("prediction", {})
    up = pred.get("up_pct", 50)
    dn = pred.get("down_pct", 50)
    if up + dn != 100:
        print(f"[call_claude] WARNING: up_pct({up}) + down_pct({dn}) = {up+dn}, normalizing down_pct to {100-up}")
        pred["down_pct"] = 100 - up
        data["prediction"] = pred

    return data


