def alert_api_failure(briefing_type: str, date_str: str, err: Exception) -> None:
    """Claude API 호출 실패를 관리자 텔레그램으로 알린다. 절대 예외를 올리지 않는다."""
    try:
        text = str(err)
        low = text.lower()
        hint = next((h for k, h in _API_FAIL_HINTS if k in low), "")
        lines = [
            "🚨 브리핑 발행 실패 — Claude API 호출 오류",
            f"종류: {briefing_type} / {date_str}",
        ]
        if hint:
            lines.append(f"원인: {hint}")
        lines.append(f"오류: {text[:400]}")
        # 평문으로 보낸다 — 오류 문자열에 <> 가 섞여도 서식 때문에 알림이 죽지 않게(§37).
        from send_telegram import send_admin_alert
        send_admin_alert("\n".join(lines))
    except Exception as e:
        # 알림 실패가 원래 오류를 가리면 안 된다.
        print(f"[call_claude] 관리자 알림 실패: {e}", file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description="Call Claude API with Prompt Caching")
    parser.add_argument("--type", choices=["kospi", "us", "kospi-close"], required=True)
    parser.add_argument("--date", default=None, help="Date string (YYYY-MM-DD)")
    parser.add_argument(
        "--no-html", action="store_true",
        help="Skip HTML generation (useful for testing)"
    )
    parser.add_argument(
        "--render", action="store_true",
        help="API 호출 없이 기존(교정된) analysis_*.json으로 텔레그램 txt·HTML만 재생성"
    )
    parser.add_argument(
        "--force-direction", default=None,
        help="prediction.direction 강제 (검증게이트 오버라이드 재생성용)",
    )
    parser.add_argument(
        "--force-refresh", action="store_true",
        help="같은 날짜에 이미 발행된 analysis_snapshot.json이 있어도 무시하고 최신 분석으로 강제 재생성 (의도적 정정 재실행용)",
    )
    args = parser.parse_args()

    date_str = args.date or datetime.now(KST).strftime("%Y-%m-%d")

    # ── 재렌더 모드: 검증 게이트 이후 교정된 analysis로 출력물만 재생성 ──
    if args.render:
        analysis_path = DATA_DIR / f"analysis_{args.type}.json"
        if not analysis_path.exists():
            print(f"[call_claude] ERROR: {analysis_path} 없음 — --render 불가", file=sys.stderr)
            sys.exit(1)
        with open(analysis_path, encoding="utf-8") as f:
            analysis = json.load(f)
        # validate 통과 후 교정된 analysis로 briefings.json 기록.
        # kospi-close는 prediction이 없다. 미국은 2026-07-14 탈퇴했다가 2026-11-03 다시 채점한다.
        if args.type in ("kospi", "us"):
            save_prediction_to_briefings(args.type, date_str, analysis)
        render_outputs(args.type, date_str, analysis, no_html=args.no_html, force=args.force_refresh)
        print(f"[call_claude] Render-only done (type={args.type})")
        return

    # ── KOSPI 마감 시황 흐름 ──
    if args.type == "kospi-close":
        try:
            analysis = call_claude_closing(date_str)
        except Exception as e:
            print(f"[call_claude] ERROR: {e}", file=sys.stderr)
            alert_api_failure("kospi-close", date_str, e)
            sys.exit(1)

        save_analysis("kospi-close", analysis)
        render_outputs("kospi-close", date_str, analysis, no_html=args.no_html, force=args.force_refresh)
        print(f"[call_claude] Done. market_title={analysis.get('market_title', '')}")
        return

    # ── 기존 kospi / us 흐름 ──
    try:
        analysis = call_claude(args.type, date_str, force_direction=args.force_direction)
    except Exception as e:
        print(f"[call_claude] ERROR calling Claude API: {e}", file=sys.stderr)
        alert_api_failure(args.type, date_str, e)
        sys.exit(1)

    save_analysis(args.type, analysis)
    render_outputs(args.type, date_str, analysis, no_html=args.no_html, force=args.force_refresh)

    print(f"[call_claude] Done. direction={analysis.get('prediction', {}).get('direction')}")


def call_claude_closing(date_str: str) -> dict:
    """KOSPI 마감 시황 분석을 Claude에게 요청한다."""
    client = anthropic.Anthropic(
        api_key=get_anthropic_api_key(),
        default_headers={"anthropic-beta": "prompt-caching-2024-07-31"},
    )

    data_file = DATA_DIR / "latest_kospi_close.json"
    if not data_file.exists():
        raise FileNotFoundError(f"마감 데이터 없음: {data_file}")
    with open(data_file, encoding="utf-8") as f:
        market_data = json.load(f)

    # investor_trading.net은 백만원 단위로 저장됨 → Claude 프롬프트용으로만 억원 변환
    import copy
    claude_data = copy.deepcopy(market_data)
    it = claude_data.get("investor_trading", {})
    if it:
        claude_data["investor_trading"] = _investor_to_eok(it)
    else:
        # 수급 데이터 미수집 시 Claude가 추정 수치를 생성하지 않도록 명시
        claude_data["_investor_trading_note"] = (
            "수급 데이터 미수집 — 타이틀·dek·brief_lines에서 외국인·기관·개인 수급 수치를 언급하거나 추정하지 말 것"
        )

    user_content = f"오늘 날짜: {date_str}\n\n"
    user_content += f"마감 데이터:\n{json.dumps(claude_data, ensure_ascii=False, indent=2)}\n"

    news_summary = load_news_summary("kospi-close")
    if news_summary:
        user_content += f"\n뉴스 요약:\n{json.dumps(news_summary, ensure_ascii=False, indent=2)}\n"

    chosen_format = FORMAT_POOL_CLOSE[0]   # 세 줄 요약 고정(2026-10-29)
    print(f"[call_claude] Selected format: {chosen_format}")

    print(f"[call_claude] Calling Claude for kospi-close (date={date_str})")
    print(f"[call_claude] User message: ~{len(user_content)//4} tokens estimated")

    last_error: Exception | None = None
    for attempt in range(3):
        if attempt > 0:
            print(f"[call_claude] JSON 파싱 실패, 재시도 {attempt}/2 ...")

        response = client.messages.create(
            model="claude-sonnet-5",
            max_tokens=2048,
            thinking={"type": "disabled"},
            system=[
                {
                    "type": "text",
                    "text": KOSPI_CLOSE_SYSTEM_PROMPT,
                    "cache_control": {"type": "ephemeral"},
                }
            ],
            messages=[{"role": "user", "content": user_content}],
        )

        usage = response.usage
        if hasattr(usage, "cache_creation_input_tokens"):
            print(f"[call_claude] Cache created: {usage.cache_creation_input_tokens} tokens")
        if hasattr(usage, "cache_read_input_tokens"):
            print(f"[call_claude] Cache hit: {usage.cache_read_input_tokens} tokens (90% discount)")
        print(f"[call_claude] Input: {usage.input_tokens}, Output: {usage.output_tokens} tokens")

        try:
            analysis = extract_json(response.content[0].text)
            analysis["analysis_format"] = chosen_format
            return analysis
        except (json.JSONDecodeError, KeyError, ValueError) as e:
            print(f"[call_claude] ERROR calling Claude API: {e}")
            last_error = e

    raise RuntimeError(f"Claude API JSON 파싱 3회 모두 실패: {last_error}")


if __name__ == "__main__":
    main()
