def call_claude(briefing_type: str, date_str: str) -> dict:
    client = anthropic.Anthropic(
        api_key=get_anthropic_api_key(),
        default_headers={"anthropic-beta": "prompt-caching-2024-07-31"},
    )

    system_prompt = KOSPI_SYSTEM_PROMPT if briefing_type == "kospi" else US_SYSTEM_PROMPT

    market_data = load_market_data(briefing_type)
    news_summary = load_news_summary(briefing_type)

    # Build user message: dynamic data (not cached)
    candidates_key = "kospi_candidates" if briefing_type == "kospi" else "us_candidates"
    # Pass only what's needed for analysis — exclude heavy market_data_js (sidebar only)
    analysis_data = {
        k: v for k, v in market_data.items()
        if k not in ("market_data_js",)  # sidebar data not needed for analysis
    }
    # Strip sparkline arrays from candidates — chart-only data, not needed for analysis
    if candidates_key in analysis_data:
        analysis_data[candidates_key] = [
            {k: v for k, v in c.items() if "sparkline" not in k}
            for c in analysis_data[candidates_key]
        ]

    user_content = f"오늘 날짜: {date_str}\n\n"
    user_content += f"시장 데이터:\n{json.dumps(analysis_data, ensure_ascii=False, indent=2)}\n\n"
    if news_summary:
        user_content += f"뉴스 요약:\n{json.dumps(news_summary, ensure_ascii=False, indent=2)}\n"

    # 휴장 직후 컨텍스트 — 한국 단독 휴장 다음날엔 EWY보다 아시아 지역 지수가 우선 시그널
    if briefing_type == "kospi" and analysis_data.get("post_holiday_catchup"):
        user_content += (
            "\n## ⚠️ 휴장 직후 컨텍스트 (post-holiday catch-up)\n"
            "어제는 한국 증시만 단독 휴장이었고 미국·아시아 주요 시장은 거래되었어요. "
            "이런 날은 EWY가 한국 갭 방향의 후행 지표가 될 수 있어요 "
            "(EWY는 미국 거래시간 sentiment를 반영하므로 한국 휴장과 무관하게 움직임).\n"
            "**우선순위 조정**:\n"
            "1. asia_regional(닛케이·항셍·상해·대만)이 모두 강세였다면 코스피 갭 상승 catch-up 가능성 우선 고려\n"
            "2. EWY 약세와 asia_regional 강세가 충돌하면 confidence를 보수적으로(50~60%대)로 설정\n"
            "3. reasons에 🌏 아시아 동조 흐름을 반드시 포함 (catch-up 효과 설명)\n"
        )
        print("[call_claude] Post-holiday catch-up context injected")

    # 다양성 가이드: 최근 시그널 카테고리 회피 (kospi 시초가 + us 브리핑)
    if briefing_type in ("kospi", "us"):
        history = load_signal_history(briefing_type)
        # 오늘 분 entry는 회피 대상에서 제외 (재실행 시 자기 자신을 회피하지 않도록)
        history = [h for h in history if h.get("date") != date_str]
        hint = build_avoidance_hint(history, days=3)
        if hint:
            user_content += hint
            print(f"[call_claude] Avoidance hint injected ({len(history[:3])} recent days)")

    print(f"[call_claude] Calling Claude API (type={briefing_type}, date={date_str})")
    print(f"[call_claude] User message: ~{len(user_content)//4} tokens estimated")

    response = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=4096,
        system=[
            {
                "type": "text",
                "text": system_prompt,
                "cache_control": {"type": "ephemeral"},  # Cache the system prompt
            }
        ],
        messages=[
            {"role": "user", "content": user_content}
        ],
    )

    # Log cache usage if available
    usage = response.usage
    if hasattr(usage, "cache_creation_input_tokens"):
        print(f"[call_claude] Cache created: {usage.cache_creation_input_tokens} tokens")
    if hasattr(usage, "cache_read_input_tokens"):
        print(f"[call_claude] Cache hit: {usage.cache_read_input_tokens} tokens (90% discount)")
    print(f"[call_claude] Input: {usage.input_tokens}, Output: {usage.output_tokens} tokens")

    raw_text = response.content[0].text
    analysis = extract_json(raw_text)

    # 응답에서 시그널 추출 후 히스토리에 저장 (kospi 시초가 + us 브리핑)
    if briefing_type in ("kospi", "us"):
        signals = extract_signal_emojis(analysis.get("reasons", []))
        save_signal_to_history(briefing_type, date_str, signals)

    return analysis


