def call_claude(briefing_type: str, date_str: str, force_direction: str | None = None) -> dict:
    client = anthropic.Anthropic(
        api_key=get_anthropic_api_key(),
        default_headers={"anthropic-beta": "prompt-caching-2024-07-31"},
    )

    system_prompt = KOSPI_SYSTEM_PROMPT if briefing_type == "kospi" else US_SYSTEM_PROMPT

    market_data = load_market_data(briefing_type)
    news_summary = load_news_summary(briefing_type)

    # Build user message: dynamic data (not cached)
    candidates_key = "kospi_candidates" if briefing_type == "kospi" else "us_candidates"
    # Pass only what's needed for analysis — exclude heavy market_data_js (sidebar only)
    analysis_data = {
        k: v for k, v in market_data.items()
        if k not in ("market_data_js",)  # sidebar data not needed for analysis
    }
    # 환율: 네이버 실시간 API 1순위, 실패 시 market_data_js 폴백.
    # yfinance USDKRW=X는 주말·공휴일 공백 문제가 있어 네이버를 우선 사용한다.
    from fetch_data import fetch_naver_usdkrw
    usdkrw = fetch_naver_usdkrw()
    if not usdkrw.get("price"):
        usd_data = (market_data.get("market_data_js") or {}).get("usd") or {}
        if usd_data.get("price"):
            usdkrw = {"price": usd_data["price"], "change_pct": usd_data.get("change_pct")}
    if usdkrw.get("price"):
        analysis_data["usdkrw"] = usdkrw
        print(f"[call_claude] usdkrw = {usdkrw['price']}원 ({usdkrw.get('change_pct'):+.2f}%)")
    # Strip sparkline arrays from candidates — chart-only data, not needed for analysis
    if candidates_key in analysis_data:
        analysis_data[candidates_key] = [
            {k: v for k, v in c.items() if "sparkline" not in k}
            for c in analysis_data[candidates_key]
        ]

    user_content = f"오늘 날짜: {date_str}\n\n"
    user_content += f"시장 데이터:\n{json.dumps(analysis_data, ensure_ascii=False, indent=2)}\n\n"
    if news_summary:
        user_content += f"뉴스 요약:\n{json.dumps(news_summary, ensure_ascii=False, indent=2)}\n"

    # 선행신호 방향 prior 주입 — SOX·선물 등 market_data_js 누락 신호도 함께 전달
    if briefing_type == "kospi":
        from leading_signal import compute_prior, format_prior_for_prompt
        prior = compute_prior(market_data)
        user_content += format_prior_for_prompt(prior)
        print(f"[call_claude] Leading-signal prior: {prior['direction']} ({prior['strength']}, score {prior['score']})")
    elif briefing_type == "us":
        # 미국은 프리마켓 선물·SOX·VIX 기반 advisory prior (방향 강제 없음)
        from leading_signal import compute_prior_us, format_prior_for_prompt_us
        prior = compute_prior_us(market_data)
        user_content += format_prior_for_prompt_us(prior)
        print(f"[call_claude] Leading-signal prior (US): {prior['direction']} ({prior['strength']}, score {prior['score']})")

    # 검증게이트 오버라이드 재생성용 — 방향 강제 (validate_analysis가 --force-direction으로 재호출). 코스피 전용.
    if force_direction and briefing_type == "kospi":
        user_content += (
            f"\n## ⛔ 방향 강제 지시 (필수)\n"
            f"이번 브리핑의 `prediction.direction`은 반드시 **{force_direction}**로 한다. "
            f"reasons·reason_title·telegram_signals 등 모든 본문을 이 방향과 일관되게 작성한다. "
            f"선행신호 prior가 전일 국내 등락보다 우선한다는 판단에 따른 강제다.\n"
        )
        print(f"[call_claude] ⛔ force_direction = {force_direction}")

    # 휴장 직후 컨텍스트 — 한국 단독 휴장 다음날엔 EWY보다 아시아 지역 지수가 우선 시그널
    if briefing_type == "kospi" and analysis_data.get("post_holiday_catchup"):
        user_content += (
            "\n## ⚠️ 휴장 직후 컨텍스트 (post-holiday catch-up)\n"
            "어제는 한국 증시만 단독 휴장이었고 미국·아시아 주요 시장은 거래되었어요. "
            "이런 날은 EWY가 한국 갭 방향의 후행 지표가 될 수 있어요 "
            "(EWY는 미국 거래시간 sentiment를 반영하므로 한국 휴장과 무관하게 움직임).\n"
            "**우선순위 조정**:\n"
            "1. asia_regional(닛케이·항셍·상해·대만)이 모두 강세였다면 코스피 갭 상승 catch-up 가능성 우선 고려\n"
            "2. EWY 약세와 asia_regional 강세가 충돌하면 confidence를 보수적으로(50~60%대)로 설정\n"
            "3. reasons에 🌏 아시아 동조 흐름을 반드시 포함 (catch-up 효과 설명)\n"
        )
        print("[call_claude] Post-holiday catch-up context injected")

    # 다양성 가이드: 최근 시그널 카테고리 회피 (kospi 예측 + us 브리핑)
    if briefing_type in ("kospi", "us"):
        history = load_signal_history(briefing_type)
        # 오늘 분 entry는 회피 대상에서 제외 (재실행 시 자기 자신을 회피하지 않도록)
        history = [h for h in history if h.get("date") != date_str]
        hint = build_avoidance_hint(history, days=3)
        if hint:
            user_content += hint
            print(f"[call_claude] Avoidance hint injected ({len(history[:3])} recent days)")

    # 하단 심층 섹션 — 2026-07-07 중단. us_linked_story·sector_focus 모두 생성하지 않는다.
    # 되살리려면 이전 커밋의 섹터/us 랜덤 택1 로직을 복원할 것.
    if briefing_type == "kospi":
        user_content += (
            "\n\n## 🎯 오늘 하단 섹션 지정\n"
            "오늘은 하단 심층 섹션을 작성하지 않는다. `us_linked_story`와 `sector_focus` 모두 반드시 null로 출력한다.\n"
        )
        print("[call_claude] Bottom section → disabled")

    # 브리핑 형식 랜덤 선택 (Python이 제어, Claude는 지시받은 형식만 사용) — bullet 가중치 최소
    chosen_format = random.choices(FORMAT_POOL, weights=FORMAT_WEIGHTS, k=1)[0]
    user_content += f"\n\n## 오늘 브리핑 근거 섹션 형식\n반드시 `{chosen_format}` 형식으로 출력하고, JSON에 `\"analysis_format\": \"{chosen_format}\"`을 포함한다.\n"
    print(f"[call_claude] Selected format: {chosen_format}")

    print(f"[call_claude] Calling Claude API (type={briefing_type}, date={date_str})")
    print(f"[call_claude] User message: ~{len(user_content)//4} tokens estimated")

    last_error: Exception | None = None
    for attempt in range(3):
        if attempt > 0:
            print(f"[call_claude] JSON 파싱 실패, 재시도 {attempt}/2 ...")

        response = client.messages.create(
            model="claude-sonnet-5",
            max_tokens=4096,
            thinking={"type": "disabled"},
            system=[
                {
                    "type": "text",
                    "text": system_prompt,
                    "cache_control": {"type": "ephemeral"},  # Cache the system prompt
                }
            ],
            messages=[
                {"role": "user", "content": user_content}
            ],
        )

        # Log cache usage if available
        usage = response.usage
        if hasattr(usage, "cache_creation_input_tokens"):
            print(f"[call_claude] Cache created: {usage.cache_creation_input_tokens} tokens")
        if hasattr(usage, "cache_read_input_tokens"):
            print(f"[call_claude] Cache hit: {usage.cache_read_input_tokens} tokens (90% discount)")
        print(f"[call_claude] Input: {usage.input_tokens}, Output: {usage.output_tokens} tokens")

        raw_text = response.content[0].text
        try:
            analysis = extract_json(raw_text)
            break
        except (json.JSONDecodeError, KeyError, ValueError) as e:
            print(f"[call_claude] ERROR calling Claude API: {e}")
            last_error = e
    else:
        raise RuntimeError(f"Claude API JSON 파싱 3회 모두 실패: {last_error}")

    # 브리핑 형식 강제 주입 — Claude가 빠뜨려도 항상 올바른 형식 보장
    analysis["analysis_format"] = chosen_format

    # 응답에서 시그널 추출 후 히스토리에 저장 (kospi 예측 + us 브리핑)
    if briefing_type in ("kospi", "us"):
        signals = extract_signal_emojis(analysis.get("reasons", []))
        save_signal_to_history(briefing_type, date_str, signals)

    # sector_focus가 채워졌으면(직접 선택 또는 us 폴백) 검증·보정 후 로테이션 이력 저장
    if briefing_type == "kospi" and analysis.get("sector_focus"):
        recent_keys = [
            h.get("sector_key")
            for h in load_sector_history("kospi")
            if h.get("date") != date_str
        ][:5]
        analysis["sector_focus"] = pick_sector(analysis.get("sector_focus"), recent_keys)
        save_sector_to_history("kospi", date_str, analysis["sector_focus"]["sector_key"])
        print(f"[call_claude] Sector focus → {analysis['sector_focus']['sector_key']}")

    return analysis


