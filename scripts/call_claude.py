def call_claude_closing(date_str: str) -> dict:
    """KOSPI 마감 시황 분석을 Claude에게 요청한다."""
    client = anthropic.Anthropic(
        api_key=get_anthropic_api_key(),
        default_headers={"anthropic-beta": "prompt-caching-2024-07-31"},
    )

    data_file = DATA_DIR / "latest_kospi_close.json"
    if not data_file.exists():
        raise FileNotFoundError(f"마감 데이터 없음: {data_file}")
    with open(data_file, encoding="utf-8") as f:
        market_data = json.load(f)

    # investor_trading.net은 백만원 단위로 저장됨 → Claude 프롬프트용으로만 억원 변환
    import copy
    claude_data = copy.deepcopy(market_data)
    it = claude_data.get("investor_trading", {})
    for actor in ["foreign", "institution", "individual"]:
        if actor in it and "net" in it[actor]:
            it[actor]["net"] = round(it[actor]["net"] / 100)
    if it:
        it["_unit"] = "억원"
    else:
        # 수급 데이터 미수집 시 Claude가 추정 수치를 생성하지 않도록 명시
        claude_data["_investor_trading_note"] = (
            "수급 데이터 미수집 — why/what/so_what에서 외국인·기관·개인 수급 수치를 언급하거나 추정하지 말 것"
        )

    user_content = f"오늘 날짜: {date_str}\n\n"
    user_content += f"마감 데이터:\n{json.dumps(claude_data, ensure_ascii=False, indent=2)}\n"

    news_summary = load_news_summary("kospi-close")
    if news_summary:
        user_content += f"\n뉴스 요약:\n{json.dumps(news_summary, ensure_ascii=False, indent=2)}\n"

    # 브리핑 형식 랜덤 선택 (Python이 제어, Claude는 지시받은 형식만 사용) — 마감 전용 풀
    chosen_format = random.choices(FORMAT_POOL_CLOSE, weights=FORMAT_WEIGHTS_CLOSE, k=1)[0]
    user_content += f"\n\n## 오늘 브리핑 근거 섹션 형식\n반드시 `{chosen_format}` 형식으로 출력하고, JSON에 `\"analysis_format\": \"{chosen_format}\"`을 포함한다.\n"
    print(f"[call_claude] Selected format: {chosen_format}")

    print(f"[call_claude] Calling Claude for kospi-close (date={date_str})")
    print(f"[call_claude] User message: ~{len(user_content)//4} tokens estimated")

    last_error: Exception | None = None
    for attempt in range(3):
        if attempt > 0:
            print(f"[call_claude] JSON 파싱 실패, 재시도 {attempt}/2 ...")

        response = client.messages.create(
            model="claude-sonnet-5",
            max_tokens=2048,
            thinking={"type": "disabled"},
            system=[
                {
                    "type": "text",
                    "text": KOSPI_CLOSE_SYSTEM_PROMPT,
                    "cache_control": {"type": "ephemeral"},
                }
            ],
            messages=[{"role": "user", "content": user_content}],
        )

        usage = response.usage
        if hasattr(usage, "cache_creation_input_tokens"):
            print(f"[call_claude] Cache created: {usage.cache_creation_input_tokens} tokens")
        if hasattr(usage, "cache_read_input_tokens"):
            print(f"[call_claude] Cache hit: {usage.cache_read_input_tokens} tokens (90% discount)")
        print(f"[call_claude] Input: {usage.input_tokens}, Output: {usage.output_tokens} tokens")

        try:
            analysis = extract_json(response.content[0].text)
            analysis["analysis_format"] = chosen_format
            return analysis
        except (json.JSONDecodeError, KeyError, ValueError) as e:
            print(f"[call_claude] ERROR calling Claude API: {e}")
            last_error = e

    raise RuntimeError(f"Claude API JSON 파싱 3회 모두 실패: {last_error}")


