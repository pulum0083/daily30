def save_telegram_message(briefing_type: str, date_str: str, analysis: dict) -> None:
    """analysis JSON → telegram_message_{type}.txt 생성 (매 실행마다 최신화)."""
    import re

    def strip_html(text: str) -> str:
        return re.sub(r"<[^>]+>", "", str(text))

    web_base = get_web_base_url()

    date_display = datetime.strptime(date_str, "%Y-%m-%d").strftime("%Y.%m.%d")

    pred = analysis.get("prediction", {})
    direction = pred.get("direction", "알 수 없음")
    up_pct = pred.get("up_pct", "?")
    down_pct = pred.get("down_pct", "?")
    confidence = pred.get("confidence", "?")
    reason_title     = strip_html(analysis.get("reason_title", ""))
    telegram_signals = analysis.get("telegram_signals", [])
    reasons          = analysis.get("reasons", [])

    # 방향에 맞는 확률 표기: 상승 우위 → up_pct, 하락 우위 → down_pct
    dir_pct   = down_pct if "하락" in str(direction) else up_pct
    dir_emoji = "📈" if "상승" in str(direction) else ("📉" if "하락" in str(direction) else "📊")

    if briefing_type == "kospi":
        header = f"🇰🇷 코스피 시초가 브리핑 | {date_display}"
        link   = f"{web_base}/briefings/ko/{date_str}/"
    else:
        header = f"🇺🇸 미국 시장 브리핑 | {date_display}"
        link   = f"{web_base}/briefings/us/{date_str}/"

    divider = "─" * 20

    lines = [
        header,
        divider,
        f"{dir_emoji} 예측: <b>{direction} ({dir_pct}%)</b>",
        f"신뢰도: <b>{confidence}%</b>",
    ]

    if reason_title:
        lines += [divider, f"💬 {reason_title}"]

    # telegram_signals 우선 사용, 없으면 reasons 앞 2개로 폴백
    signals = telegram_signals[:2] if telegram_signals else [strip_html(r) for r in reasons[:2]]
    if signals:
        lines += ["", "핵심 시그널:"]
        for s in signals:
            lines.append(f"• {strip_html(s)}")

    lines += [divider, f"🔗 상세 분석 → {link}"]

    msg = "\n".join(lines)
    path = DATA_DIR / f"telegram_message_{briefing_type}.txt"
    with open(path, "w", encoding="utf-8") as f:
        f.write(msg)
    print(f"[call_claude] Telegram message saved → {path}")


def extract_json(text: str) -> dict:
    """Parse JSON from Claude's response, stripping any accidental markdown fences."""
    text = text.strip()
    # Strip markdown code fences if present
    if text.startswith("```"):
        lines = text.split("\n")
        # Remove first line (```json or ```) and last line (```)
        text = "\n".join(lines[1:-1] if lines[-1].strip() == "```" else lines[1:])
    data = json.loads(text)

    # Guarantee up_pct + down_pct == 100
    pred = data.get("prediction", {})
    up = pred.get("up_pct", 50)
    dn = pred.get("down_pct", 50)
    if up + dn != 100:
        print(f"[call_claude] WARNING: up_pct({up}) + down_pct({dn}) = {up+dn}, normalizing down_pct to {100-up}")
        pred["down_pct"] = 100 - up
        data["prediction"] = pred

    return data


